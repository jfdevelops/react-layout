import {
  cp,
  mkdtemp,
  readdir,
  readFile,
  rm,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { listVersions, writeDocsNavigation } from './docs-manifest.mjs';
import { unwrapMarkdownParagraphs } from './markdown-paragraphs.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsRequire = createRequire(path.join(root, 'tools/docs/package.json'));
const { Application } = await import(
  pathToFileURL(docsRequire.resolve('typedoc')).href
);

async function addPageMetadata(directory, isRoot = true) {
  const entries = await readdir(directory, {
    withFileTypes: true,
  });
  const pages = [];

  for (const entry of entries.sort((left, right) =>
    left.name.localeCompare(right.name, 'en'),
  )) {
    const location = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      await addPageMetadata(location, false);
      pages.push(entry.name);
    } else if (entry.name.endsWith('.md')) {
      const name = entry.name.slice(0, -3);
      const isLanding = isRoot && name === 'index';
      const title =
        name === 'index'
          ? isLanding
            ? 'API reference'
            : path.basename(directory)
          : name;
      const description = isLanding
        ? 'API documentation generated from the public TypeScript entry point.'
        : `Generated API documentation for ${title}.`;
      const body = (await readFile(location, 'utf8'))
        .replace(/\r\n/g, '\n')
        .trim();
      const metadata = `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---`;

      await writeFile(
        location,
        `${metadata}\n\n<!-- Generated by pnpm generate-docs. Do not edit directly. -->\n\n${unwrapMarkdownParagraphs(body)}\n`,
      );
      pages.push(name);
    }
  }

  pages.sort((left, right) =>
    left === 'index'
      ? -1
      : right === 'index'
        ? 1
        : left.localeCompare(right, 'en'),
  );
  await writeFile(
    path.join(directory, 'meta.json'),
    `${JSON.stringify(
      {
        title: isRoot ? 'API reference' : path.basename(directory),
        pages,
      },
      null,
      2,
    )}\n`,
  );
}

/** The current version of each framework gets a generated API reference. */
function referenceOutputs() {
  const outputs = listVersions(root)
    .frameworks.flatMap((framework) => framework.versions)
    .map((version) => version.generatedReference)
    .filter(Boolean);

  if (outputs.length === 0) {
    throw new Error(
      'No docs/framework/<framework>/v<major> directory matches the core package major.',
    );
  }

  return outputs;
}

async function generateReference(outputs) {
  const temporary = await mkdtemp(
    path.join(tmpdir(), 'react-layout-reference-'),
  );

  try {
    const app = await Application.bootstrapWithPlugins({
      plugin: [docsRequire.resolve('typedoc-plugin-markdown')],
      entryPoints: [
        path.join(root, 'packages/core/src/index.ts').split(path.sep).join('/'),
      ],
      tsconfig: path.join(root, 'tools/docs/tsconfig.json'),
      outputs: [
        {
          name: 'markdown',
          path: temporary,
        },
      ],
      readme: 'none',
      entryFileName: 'index',
      hidePageHeader: true,
      hidePageTitle: true,
      hideBreadcrumbs: true,
      useCodeBlocks: true,
      excludePrivate: true,
      excludeProtected: true,
      excludeInternal: true,
      excludeExternals: true,
      disableSources: true,
      gitRevision: 'main',
    });
    const project = await app.convert();

    if (!project || app.logger.hasErrors()) {
      throw new Error(
        'TypeDoc conversion failed; existing reference pages were preserved.',
      );
    }

    await app.generateOutputs(project);

    if (app.logger.hasErrors()) {
      throw new Error(
        'TypeDoc rendering failed; existing reference pages were preserved.',
      );
    }
    await addPageMetadata(temporary);

    for (const output of outputs) {
      await rm(output, {
        recursive: true,
        force: true,
      });
      await cp(temporary, output, {
        recursive: true,
      });

      console.log(
        `Generated reference: ${path.relative(root, output).split(path.sep).join('/')}`,
      );
    }
  } finally {
    await rm(temporary, {
      recursive: true,
      force: true,
    });
  }
}

/** Writes the API reference, docs/docs.json and every meta.json. */
export async function generateDocs() {
  await generateReference(referenceOutputs());

  const { metaFiles } = writeDocsNavigation({
    root,
  });

  console.log(
    `Generated navigation: docs/docs.json and ${metaFiles.size} meta.json files`,
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await generateDocs();
}
